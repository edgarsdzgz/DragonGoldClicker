"""Bring the official pixel art into the game.

Reads the register `_dev/art/official/OFFICIAL.md` (the art session's library, never written to
here), copies every listed PNG into `assets/art/<group>/`, and writes the typed manifest
`src/art/manifest.ts`. The plot and gate layouts are embedded in the manifest from their JSON.
`assets/art/` belongs to this script: files no longer listed are removed.

Strips are named `<name>_strip<N>.png` and get the id `<name>_anim`; their speed comes from the
register's "(N fps)", else 6.
Run from the repo root after an approved art change: python scripts/import-art.py
"""
import json
import pathlib
import re
import shutil

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
OFFICIAL = ROOT / "_dev" / "art" / "official"
ASSETS = ROOT / "assets" / "art"
MANIFEST = ROOT / "src" / "art" / "manifest.ts"
DEFAULT_FPS = 6

ROW = re.compile(r"^\| `([^`]+)` \| ([^|]*) \| ([^|]*) \|")
STRIP = re.compile(r"^(.*)_strip(\d+)$")
FPS = re.compile(r"(\d+) fps")


def rows():
    for line in (OFFICIAL / "OFFICIAL.md").read_text(encoding="utf-8").splitlines():
        m = ROW.match(line)
        if m:
            yield m.group(1), m.group(3).strip()


def const_name(stem):
    return re.sub(r"[^A-Za-z0-9]+", "_", stem).upper()


def main():
    sprites = []
    layouts = {}
    # Read and check everything first; nothing in assets/art is touched until it all passes
    for rel, what in rows():
        src = OFFICIAL / rel
        if rel.endswith(".json"):
            layouts[pathlib.Path(rel).stem] = json.loads(src.read_text(encoding="utf-8"))
            continue
        if not rel.endswith(".png"):
            continue
        stem = pathlib.Path(rel).stem
        w, h = Image.open(src).size
        strip = STRIP.match(stem)
        frames = int(strip.group(2)) if strip else 1
        if w % frames:
            raise SystemExit(f"{rel}: width {w} does not split into {frames} frames")
        fps_match = FPS.search(what)
        fps = (int(fps_match.group(1)) if fps_match else DEFAULT_FPS) if frames > 1 else 0
        sprites.append((f"{strip.group(1)}_anim" if strip else stem, rel, w // frames, h, frames, fps, what))

    if not sprites:
        raise SystemExit("the register lists no sprites; has the table format changed?")
    ids = [s[0] for s in sprites]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        raise SystemExit(f"duplicate sprite ids: {sorted(dupes)}")
    consts = [const_name(n) for n in layouts]
    if len(set(consts)) != len(consts):
        raise SystemExit(f"layout names collide: {sorted(layouts)}")

    wanted = set()
    for _, rel, *_rest in sprites:
        dest = ASSETS / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(OFFICIAL / rel, dest)
        wanted.add(dest)
    for f in ASSETS.rglob("*"):
        if f.is_file() and f not in wanted:
            f.unlink()
    for d in sorted(ASSETS.rglob("*"), reverse=True):
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()

    out = [
        "// GENERATED by scripts/import-art.py from _dev/art/official/OFFICIAL.md. Do not edit;",
        "// rerun the script after an approved art change.",
        "import type { ImageSourcePropType } from 'react-native'",
        "",
        "export interface SpriteDef {",
        "  source: ImageSourcePropType",
        "  /** Native size of one frame, in art pixels */",
        "  w: number",
        "  h: number",
        "  /** Frames laid side by side in the file (1 for a still) */",
        "  frames: number",
        "  /** Playback speed of a strip (0 for a still) */",
        "  fps: number",
        "  /** What it is, from the register */",
        "  label: string",
        "}",
        "",
        "export const SPRITES = {",
    ]
    for sid, rel, w, h, frames, fps, what in sprites:
        out.append(
            f"  {json.dumps(sid)}: {{ source: require('../../assets/art/{rel}'), w: {w}, h: {h}, "
            f"frames: {frames}, fps: {fps}, label: {json.dumps(what)} }},"
        )
    out += ["} satisfies Record<string, SpriteDef>", "", "export type SpriteId = keyof typeof SPRITES", ""]
    for name, data in sorted(layouts.items()):
        const = const_name(name)
        out.append(f"export const {const} = {json.dumps(data, indent=2)} as const")
        out.append("")
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(sprites)} sprites, {len(layouts)} layouts -> {MANIFEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
